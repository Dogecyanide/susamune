#ifndef SUSAMUNE_TRANSFER_LAYOUT_H
#define SUSAMUNE_TRANSFER_LAYOUT_H
#include "mem2_map.h"
#include "transfer_lease.h"

/* Runtime ABI 0x10002 only; legacy constants retain their original ownership. */
#define SUSAMUNE_TRANSFER_RECLAIM_SIZE 0x00400000u
#define SUSAMUNE_TRANSFER_STAGE_SIZE (SUSAMUNE_STATE_STAGING_SIZE + \
    SUSAMUNE_GHOST_FILE_TRANSFER_SIZE - SUSAMUNE_TRANSFER_RECLAIM_SIZE)
#define SUSAMUNE_TRANSFER_STAGE_PHYS_BASE NIN_MEM2_SEGABOOT_PHYS_BASE
#define SUSAMUNE_TRANSFER_STAGE_PPC_BASE NIN_MEM2_SEGABOOT_PPC_BASE
#define SUSAMUNE_TRANSFER_IMPORT_WINDOW_SIZE SUSAMUNE_STATE_CODEC_WORKSPACE_SIZE
#define SUSAMUNE_TRANSFER_IMPORT_WINDOW_OFFSET \
    (SUSAMUNE_TRANSFER_STAGE_SIZE - SUSAMUNE_TRANSFER_IMPORT_WINDOW_SIZE)
#if SUSAMUNE_TRANSFER_IMPORT_WINDOW_SIZE > SUSAMUNE_TRANSFER_STAGE_SIZE || (SUSAMUNE_TRANSFER_IMPORT_WINDOW_OFFSET & 31u)
#error Import window must fit and start on a cache line
#endif
#define SUSAMUNE_TRANSFER_POOL_THIRD_PHYS_BASE \
    (SUSAMUNE_TRANSFER_STAGE_PHYS_BASE + SUSAMUNE_TRANSFER_STAGE_SIZE)
#define SUSAMUNE_TRANSFER_POOL_THIRD_PPC_BASE \
    (SUSAMUNE_TRANSFER_STAGE_PPC_BASE + SUSAMUNE_TRANSFER_STAGE_SIZE)
#define SUSAMUNE_TRANSFER_POOL_THIRD_SIZE \
    (SUSAMUNE_STATE_STAGING_SIZE - SUSAMUNE_TRANSFER_STAGE_SIZE)
#define SUSAMUNE_TRANSFER_POOL_FOURTH_PHYS_BASE SUSAMUNE_GHOST_FILE_TRANSFER_PHYS_BASE
#define SUSAMUNE_TRANSFER_POOL_FOURTH_PPC_BASE SUSAMUNE_GHOST_FILE_TRANSFER_PPC_BASE
#define SUSAMUNE_TRANSFER_POOL_FOURTH_SIZE SUSAMUNE_GHOST_FILE_TRANSFER_SIZE
#define SUSAMUNE_TRANSFER_POOL_FIFTH_PHYS_BASE \
    (NIN_MEM2_DI_SCRATCH_PHYS_BASE + NIN_MEM2_DI_SCRATCH_RUNTIME_SIZE)
#define SUSAMUNE_TRANSFER_POOL_FIFTH_PPC_BASE \
    (NIN_MEM2_DI_SCRATCH_PPC_BASE + NIN_MEM2_DI_SCRATCH_RUNTIME_SIZE)
#define SUSAMUNE_TRANSFER_POOL_FIFTH_SIZE \
    (NIN_MEM2_DI_SCRATCH_SIZE - NIN_MEM2_DI_SCRATCH_RUNTIME_SIZE)
#define SUSAMUNE_TRANSFER_POOL_SIZE \
    (SUSAMUNE_STATE_POOL_EXPANDED_SIZE + SUSAMUNE_TRANSFER_RECLAIM_SIZE + \
     SUSAMUNE_TRANSFER_POOL_FIFTH_SIZE)
#define SUSAMUNE_TRANSFER_PHYS_PTR ((volatile TWLeaseControl *) \
    (SUSAMUNE_CONSOLE_GHOST_TRANSFER_PHYS_BASE + TW_LEASE_REQUEST_OFFSET))
#define SUSAMUNE_TRANSFER_PPC_PTR ((volatile TWLeaseControl *) \
    (SUSAMUNE_CONSOLE_GHOST_TRANSFER_PPC_BASE + TW_LEASE_REQUEST_OFFSET))
#if SUSAMUNE_TRANSFER_POOL_THIRD_PHYS_BASE + SUSAMUNE_TRANSFER_POOL_THIRD_SIZE != NIN_MEM2_DI_SCRATCH_PHYS_BASE || SUSAMUNE_TRANSFER_POOL_FOURTH_PHYS_BASE + SUSAMUNE_TRANSFER_POOL_FOURTH_SIZE != SUSAMUNE_STATE_STORAGE_PHYS_BASE || SUSAMUNE_TRANSFER_POOL_FIFTH_PHYS_BASE + SUSAMUNE_TRANSFER_POOL_FIFTH_SIZE != NIN_MEM2_LOADER_DISC_PHYS_BASE
#error Shared transfer ABI ranges overlap live storage
#endif
#if TW_LEASE_REQUEST_OFFSET + 128u > SUSAMUNE_GHOST_TRANSFER_MAILBOX_HEADER_SIZE || SUSAMUNE_TRANSFER_STAGE_SIZE < SUSAMUNE_GHOST_FILE_TRANSFER_SIZE
#error Shared transfer control or payload does not fit
#endif
#endif
