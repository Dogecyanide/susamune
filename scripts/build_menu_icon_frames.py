"""Convert approved alternate artwork to small, transparent GameCube textures."""
from pathlib import Path
import struct

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


ASSETS = ((0, "controller", "ControllerPose"),)


def encode_texture(name):
    image = Image.open(ROOT / f"data/menu_icons/{name}-pose2.png").convert("RGBA")
    image = image.crop(image.getchannel("A").point(lambda value: 255 if value >= 16 else 0).getbbox())
    image.thumbnail((40, 36), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (40, 36))
    canvas.alpha_composite(image, ((40 - image.width) // 2, (36 - image.height) // 2))
    palette_image = canvas.quantize(colors=32, method=Image.Quantize.FASTOCTREE)
    colors = palette_image.getpalette("RGBA")
    data = bytearray(1536)
    data[0:2] = bytes((9, 2))
    struct.pack_into(">HH", data, 2, 40, 36)
    data[8:10] = bytes((1, 2))
    struct.pack_into(">H", data, 10, 32)
    struct.pack_into(">I", data, 12, 32)
    data[20] = data[21] = data[24] = 1
    struct.pack_into(">I", data, 28, 96)
    for i in range(32):
        r, g, b, a = colors[i * 4:i * 4 + 4]
        word = (0x8000 | (r >> 3) << 10 | (g >> 3) << 5 | (b >> 3)) if a >= 224 else (
            (a >> 5) << 12 | (r >> 4) << 8 | (g >> 4) << 4 | (b >> 4))
        struct.pack_into(">H", data, 32 + i * 2, word)
    pixels = palette_image.load()
    for y in range(36):
        for x in range(40):
            data[96 + (y // 4 * 5 + x // 8) * 32 + (y & 3) * 8 + (x & 7)] = pixels[x, y]
    return data, palette_image.convert("RGBA")


def main():
    lines = ["// Generated by scripts/build_menu_icon_frames.py.",
             '#include "susamune/menu_icon_frames.hxx"', "", "namespace MenuIconFrames {"]
    folder = ROOT / "build/pr22-icon-refs"
    folder.mkdir(exist_ok=True)
    for _, name, symbol in ASSETS:
        data, preview = encode_texture(name)
        lines.append(f"const unsigned char {symbol}[PoseBytes] __attribute__((aligned(32))) = {{")
        lines.extend("    " + ", ".join(f"0x{x:02x}" for x in data[i:i + 16]) + ","
                     for i in range(0, len(data), 16))
        lines.append("};")
        preview.save(folder / f"{name}-pose2-menu.png")
    lines.extend(["const unsigned char *get(unsigned index) {", "    switch (index) {"])
    lines.extend(f"    case {index}: return {symbol};" for index, _, symbol in ASSETS)
    lines.extend(["    default: return nullptr;", "    }", "}", "}", ""])
    (ROOT / "src/menu_icon_frames.cpp").write_text("\n".join(lines))
    print(f"{len(ASSETS)} alternate frame(s): 40x36, 32 colours, 1536 bytes each")


if __name__ == "__main__":
    main()
